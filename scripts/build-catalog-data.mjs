import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";

const args = new Set(process.argv.slice(2));
const shouldGenerate = args.has("--generate") || args.size === 0;
const shouldWriteDist = args.has("--dist") || args.size === 0;
const shouldCheck = args.has("--check") || args.size === 0;

const ROOT = findRoot(process.cwd());
const SRC_DATA_DIR = join(ROOT, "packages", "catalog", "src", "data");
const SHARDS_DIR = join(SRC_DATA_DIR, "shards");
const SRC_INDEX_PATH = join(SRC_DATA_DIR, "index.ts");
const SRC_SHARDS_PATH = join(ROOT, "packages", "catalog", "src", "shards.ts");
const DIST_DATA_DIR = join(ROOT, "packages", "catalog", "dist", "data");
const CATALOG_PACKAGE_PATH = join(ROOT, "packages", "catalog", "package.json");
const BLOCKSCOUT_CHAINS_SRC = join(SRC_DATA_DIR, "blockscout-chains.json");

function findRoot(start) {
  let dir = resolve(start);
  while (true) {
    if (existsSync(join(dir, "pnpm-workspace.yaml"))) return dir;
    const parent = dirname(dir);
    if (parent === dir) throw new Error("Could not find repository root");
    dir = parent;
  }
}

function listJsonFiles(dir) {
  const files = [];
  walk(dir, files);
  return files.sort((a, b) => relative(SHARDS_DIR, a).localeCompare(relative(SHARDS_DIR, b)));
}

function walk(dir, files) {
  if (!existsSync(dir)) throw new Error(`Missing catalog shards directory: ${dir}`);
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, files);
    } else if (entry.isFile() && entry.name.endsWith(".json") && entry.name !== "_index.json") {
      files.push(full);
    }
  }
}

function listManifestFiles(dir) {
  const manifests = [];
  walkManifests(dir, manifests);
  return manifests.sort((a, b) => relative(SHARDS_DIR, a).localeCompare(relative(SHARDS_DIR, b)));
}

function walkManifests(dir, manifests) {
  if (!existsSync(dir)) return;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walkManifests(full, manifests);
    else if (entry.isFile() && entry.name === "_index.json") manifests.push(full);
  }
}

function loadShards(files) {
  const shards = [];
  for (const file of files) {
    const raw = readFileSync(file, "utf8");
    let entries;
    try {
      entries = JSON.parse(raw);
    } catch (error) {
      throw new Error(`${relative(ROOT, file)} is invalid JSON: ${error.message}`);
    }
    if (!Array.isArray(entries)) throw new Error(`${relative(ROOT, file)} must be a JSON array`);
    shards.push({ id: shardId(file), file, entries });
  }
  return shards;
}

function shardId(file) {
  return relative(SHARDS_DIR, file).replace(/\\/g, "/").replace(/\.json$/, "");
}

function importPath(file) {
  return `./${relative(SRC_DATA_DIR, file).replace(/\\/g, "/")}`;
}

function importName(index) {
  return `shard${String(index).padStart(3, "0")}`;
}

function shardAlias(id) {
  if (id.startsWith("ecosystems/sourcify-signatures/")) {
    return id.replace(/^ecosystems\//, "");
  }
  const parts = id.split("/");
  return parts[parts.length - 1];
}

function renderIndex(shards) {
  const rows = shards.map((shard) => `  ${JSON.stringify(shard.id)},`).join("\n");

  return `// Generated by scripts/build-catalog-data.mjs. Do not edit by hand.\nimport { createRequire } from "node:module";\nimport type { CatalogEntry } from "../types.js";\n\nexport interface CatalogShard {\n  id: string;\n  entries: CatalogEntry[];\n}\n\nconst requireCatalogJson = createRequire(import.meta.url);\nconst SHARD_IDS = [\n${rows}\n] as const;\n\nfunction loadShardEntries(id: string): CatalogEntry[] {\n  return requireCatalogJson(\`./shards/\${id}.json\`) as CatalogEntry[];\n}\n\nexport const CATALOG_SHARDS: CatalogShard[] = SHARD_IDS.map((id) => ({\n  id,\n  entries: loadShardEntries(id),\n}));\n\nexport const CATALOG_ENTRIES: CatalogEntry[] = CATALOG_SHARDS.flatMap((shard) => shard.entries);\n`;
}

function renderShardLoader(shards) {
  const aliases = uniqueShardAliases(shards);
  const allNames = [];
  const seen = new Set();
  const nameToId = {};
  const addName = (name, id) => {
    if (!seen.has(name)) {
      seen.add(name);
      allNames.push(name);
    }
    nameToId[name] = id;
  };

  for (const shard of shards) {
    for (const name of [shard.id, shardAlias(shard.id)]) {
      if (name === shardAlias(shard.id) && aliases.get(name) !== shard.id) continue;
      addName(name, shard.id);
    }
  }

  const sourcifyBucketIds = shards
    .map((shard) => shard.id)
    .filter((id) => id.startsWith("ecosystems/sourcify-signatures/"))
    .sort();
  if (sourcifyBucketIds.length > 0) {
    addName("ecosystems/sourcify-signatures", sourcifyBucketIds);
    addName("sourcify-signatures", sourcifyBucketIds);
  }

  return `// Generated by scripts/build-catalog-data.mjs. Do not edit by hand.\nimport type { CatalogEntry } from "./types.js";\n\nexport const SHARD_NAMES = ${JSON.stringify(allNames, null, 2)} as const;\nexport type ShardName = typeof SHARD_NAMES[number];\n\nconst SHARD_NAME_TO_ID: Record<ShardName, string | readonly string[]> = ${JSON.stringify(nameToId, null, 2)};\n\nexport async function loadShard(name: ShardName): Promise<CatalogEntry[]> {\n  const id = SHARD_NAME_TO_ID[name];\n  if (!id) throw new Error(\`Unknown catalog shard: \${name}\`);\n  if (Array.isArray(id)) {\n    const loaded = await Promise.all(id.map(async (shardId) => {\n      const shard = await import(\`./data/shards/\${shardId}.json\`, { with: { type: "json" } });\n      return shard.default as unknown as CatalogEntry[];\n    }));\n    return loaded.flat();\n  }\n  const loaded = await import(\`./data/shards/\${id}.json\`, { with: { type: "json" } });\n  return loaded.default as unknown as CatalogEntry[];\n}\n`;
}

function checkEntries(shards) {
  const ids = new Map();
  let total = 0;
  for (const shard of shards) {
    total += shard.entries.length;
    for (const entry of shard.entries) {
      if (!entry || typeof entry !== "object") throw new Error(`${shard.id} contains a non-object entry`);
      if (typeof entry.id !== "string" || entry.id.length === 0) throw new Error(`${shard.id} contains an entry without id`);
      const existing = ids.get(entry.id);
      if (existing) throw new Error(`Duplicate catalog id ${entry.id} in ${existing} and ${shard.id}`);
      ids.set(entry.id, shard.id);
    }
  }
  return total;
}

function writeDist(shards) {
  mkdirSync(DIST_DATA_DIR, { recursive: true });
  const distShards = join(DIST_DATA_DIR, "shards");
  rmSync(distShards, { recursive: true, force: true });

  for (const shard of shards) {
    const rel = relative(SHARDS_DIR, shard.file);
    const out = join(distShards, rel);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, `${JSON.stringify(shard.entries, null, 2)}\n`);
  }

  for (const manifest of listManifestFiles(SHARDS_DIR)) {
    const rel = relative(SHARDS_DIR, manifest);
    const out = join(distShards, rel);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, readFileSync(manifest, "utf8"));
  }

  const merged = shards.flatMap((shard) => shard.entries).sort((a, b) => a.id.localeCompare(b.id));
  writeFileSync(join(DIST_DATA_DIR, "errors.json"), `${JSON.stringify(merged, null, 2)}\n`);
  writeFileSync(
    join(ROOT, "packages", "catalog", "dist", "data.js"),
    `if (typeof process !== "undefined" && !process.env.REVERTWTF_SILENCE_DATA_WARN) {\n  console.warn("[revertwtf] @revertwtf/catalog/data is deprecated; use @revertwtf/catalog/data-full or @revertwtf/catalog/data/shards/<name>.");\n}\nexport { default } from "./data/errors.json" with { type: "json" };\n`,
  );
  writeFileSync(
    join(ROOT, "packages", "catalog", "dist", "data.d.ts"),
    `import type { CatalogEntry } from "./types.js";\ndeclare const entries: CatalogEntry[];\nexport default entries;\n`,
  );
  writeFileSync(
    join(ROOT, "packages", "catalog", "dist", "data-full.d.ts"),
    `import type { CatalogEntry } from "./types.js";\ndeclare const entries: CatalogEntry[];\nexport default entries;\n`,
  );

  if (existsSync(BLOCKSCOUT_CHAINS_SRC)) {
    writeFileSync(join(DIST_DATA_DIR, "blockscout-chains.json"), readFileSync(BLOCKSCOUT_CHAINS_SRC, "utf8"));
  }
}

function uniqueShardAliases(shards) {
  const aliases = new Map();
  const collisions = new Set();
  for (const shard of shards) {
    const alias = shardAlias(shard.id);
    if (aliases.has(alias)) collisions.add(alias);
    else aliases.set(alias, shard.id);
  }
  for (const collision of collisions) aliases.delete(collision);
  return aliases;
}

function catalogShardExports(shards) {
  const exports = {};
  const aliases = uniqueShardAliases(shards);
  for (const shard of shards) {
    const target = {
      import: `./dist/data/shards/${shard.id}.json`,
      default: `./dist/data/shards/${shard.id}.json`,
    };
    exports[`./data/shards/${shard.id}`] = target;
    const alias = shardAlias(shard.id);
    if (aliases.get(alias) === shard.id && alias !== shard.id) {
      exports[`./data/shards/${alias}`] = target;
    }
  }
  return Object.fromEntries(Object.entries(exports).sort(([a], [b]) => a.localeCompare(b)));
}

function updateCatalogPackageExports(shards) {
  const pkg = JSON.parse(readFileSync(CATALOG_PACKAGE_PATH, "utf8"));
  const nextExports = {};
  for (const [key, value] of Object.entries(pkg.exports)) {
    if (key.startsWith("./data/shards/")) continue;
    if (key === "./data") {
      nextExports[key] = {
        types: "./dist/data.d.ts",
        import: "./dist/data.js",
      };
      continue;
    }
    nextExports[key] = value;
  }
  nextExports["./data-full"] = {
    types: "./dist/data-full.d.ts",
    import: "./dist/data/errors.json",
    default: "./dist/data/errors.json",
  };
  nextExports["./shards"] = {
    types: "./dist/shards.d.ts",
    import: "./dist/shards.js",
  };
  Object.assign(nextExports, catalogShardExports(shards));
  pkg.exports = nextExports;
  writeFileSync(CATALOG_PACKAGE_PATH, `${JSON.stringify(pkg, null, 2)}\n`);
}

const files = listJsonFiles(SHARDS_DIR);
const shards = loadShards(files);
const total = shouldCheck ? checkEntries(shards) : shards.reduce((sum, shard) => sum + shard.entries.length, 0);

if (shouldGenerate) {
  writeFileSync(SRC_INDEX_PATH, renderIndex(shards));
  writeFileSync(SRC_SHARDS_PATH, renderShardLoader(shards));
  updateCatalogPackageExports(shards);
}

if (shouldWriteDist) {
  writeDist(shards);
}

console.log(`catalog data: ${shards.length} shards, ${total} entries`);
